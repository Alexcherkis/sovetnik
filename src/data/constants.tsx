const BlogCTA = ({ text, link, label }: { text: string, link: string, label: string }) => (
  <div className="my-10 p-8 bg-brand-50 border border-brand-100 rounded-xl text-center">
    <p className="text-lg md:text-xl font-bold text-brand-900 mb-6 leading-relaxed font-serif">
      {text}
    </p>
    <button
      onClick={() => {
        // If the link is internal to /contacts, open modal. Otherwise follow link.
        if (link === '/contacts' || link.includes('services')) {
          const event = new CustomEvent('openContactModal', { detail: { service: `CTA Блога: ${label}` } });
          window.dispatchEvent(event);
        } else {
          window.location.href = link;
        }
      }}
      className="inline-flex items-center justify-center px-8 py-4 bg-brand-900 text-white font-serif font-bold rounded-lg shadow-lg hover:bg-brand-red transition-colors"
    >
      {label}
    </button>
  </div>
);

